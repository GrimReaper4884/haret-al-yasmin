"""Exports an arena authored in Blender (docs/STORY_PLAN.md §8.3, S1-M03) to config:

  src/shared/Config/ArenaLayouts/<id>.luau   the kit modules to place, sorted, deterministic
  src/shared/Config/Arenas.luau              its entry (road, bounds, spawns, gate yaw, theme), rewritten
                                             between "BEGIN/END GENERATED <id>" markers

    "C:/Program Files/Blender Foundation/Blender 5.2/blender.exe" -b assets/blender/arenas/<id>.blend -P tools/blender/export_layout.py

The scene holds: objects with a "module" property (kit modules), a `Path` curve (the enemy road;
twin-gate arenas add `Path_2`), a `Bounds` plane, empties `PlayerSpawn`, `Spawn_1`, `Gate`. The
scene property "arena_id" names the arena. Axis mapping (see arena_olive_press.py): x = -x_blender,
z = y_blender, yaw = Blender Z rotation in degrees. Numbers are rounded (0.1 stud, 1 degree) so the
files regenerate byte-identical from the same .blend.
"""

import math
from pathlib import Path

import bpy

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "src" / "shared" / "Config" / "ArenaLayouts"


def r1(v):
    v = round(v, 1)
    return 0.0 if v == 0 else v


def fmt(v):
    s = f"{r1(v):.1f}"
    return s[:-2] if s.endswith(".0") else s


def local(x_b, y_b):
    return (r1(-x_b), r1(y_b))


def road(name):
    o = bpy.data.objects.get(name)
    if not o:
        return None
    pts = []
    for sp in o.data.splines:
        for p in sp.points:
            w = o.matrix_world @ p.co.to_3d()
            pts.append(local(w.x, w.y))
    return pts


def main():
    scene = bpy.context.scene
    aid = scene.get("arena_id")
    assert aid, "scene property arena_id missing"
    mods = []
    for o in scene.objects:
        m = o.get("module")
        if m:
            x, z = local(o.location.x, o.location.y)
            yaw = round(math.degrees(o.rotation_euler.z)) % 360
            mods.append((m, x, z, yaw, r1(o.scale.x * 100) / 100 if abs(o.scale.x - 1) > 1e-3 else 1))
    mods.sort()
    lines = [
        "--!strict",
        f"-- GENERATED by tools/blender/export_layout.py from assets/blender/arenas/{aid}.blend: do not edit by",
        "-- hand; move modules in Blender and re-export. Kit modules placed by server/World/KitLayout",
        "-- (arena-local studs; yaw in degrees, 0 = the module's front faces -Z).",
        "",
        "export type Placement = { module: string, x: number, z: number, yaw: number, scale: number }",
        "",
        "local layout: { Placement } = {",
    ]
    for m, x, z, yaw, s in mods:
        lines.append(f'\t{{ module = "{m}", x = {fmt(x)}, z = {fmt(z)}, yaw = {yaw}, scale = {fmt(s) if s != 1 else 1} }},')
    lines += ["}", "", "return layout", ""]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{aid}.luau").write_bytes("\n".join(lines).encode("utf-8"))

    paths = [p for p in (road("Path"), road("Path_2")) if p]
    b = bpy.data.objects["Bounds"]
    corners = [b.matrix_world @ v.co for v in b.data.vertices]
    xs = [local(c.x, c.y)[0] for c in corners]
    zs = [local(c.x, c.y)[1] for c in corners]
    ps = bpy.data.objects["PlayerSpawn"].location
    sx, sz = local(ps.x, ps.y)
    gate = paths[0][-1]
    before = paths[0][-2]
    # Config/Arenas' convention (orchard, siege): both yaws are atan2(dx, dz) of the road direction at
    # that end, i.e. the gate faces back up the road and the spawn gate faces away from it.
    gate_yaw = round(math.degrees(math.atan2(gate[0] - before[0], gate[1] - before[1]))) % 360
    a, n = paths[0][0], paths[0][1]
    spawn_yaw = round(math.degrees(math.atan2(n[0] - a[0], n[1] - a[1]))) % 360

    def pts(p):
        return "{ " + ", ".join(f"{{ {fmt(x)}, {fmt(z)} }}" for x, z in p) + " }"

    # The Config/Arenas entry, between generated markers (config modules cannot require each other).
    T, NL = "\t", "\n"
    entry = [
        f"{T}-- BEGIN GENERATED {aid} (tools/blender/export_layout.py from assets/blender/arenas/{aid}.blend)",
        f"{T}{aid} = {{",
        f'{T}{T}nameKey = "{scene.get("arena_name_key", "arena." + aid + ".name")}",',
        f"{T}{T}path = {pts(paths[0])},",
    ]
    if len(paths) > 1:
        entry.append(f"{T}{T}paths = {{ " + ", ".join(pts(p) for p in paths) + " },")
    entry += [
        f"{T}{T}bounds = {{ {fmt(min(xs))}, {fmt(min(zs))}, {fmt(max(xs))}, {fmt(max(zs))} }},",
        f"{T}{T}gateYaw = {gate_yaw},",
        f"{T}{T}spawnYaw = {spawn_yaw},",
        f"{T}{T}playerSpawn = {{ {fmt(sx)}, {fmt(sz)} }},",
        f'{T}{T}seed = "{scene.get("arena_seed", aid)}",',
        f'{T}{T}theme = "{scene.get("arena_theme", "orchard")}",',
        f'{T}{T}kit = "{aid}", -- server/World/KitLayout places Config/ArenaLayouts/{aid}',
        f"{T}}},",
        f"{T}-- END GENERATED {aid}",
    ]
    arenas = ROOT / "src" / "shared" / "Config" / "Arenas.luau"
    text = arenas.read_text(encoding="utf-8")
    begin = f"{T}-- BEGIN GENERATED {aid} "
    end_marker = f"{T}-- END GENERATED {aid}{NL}"
    if begin in text:
        a = text.index(begin)
        b = text.index(end_marker, a) + len(end_marker)
        text = text[:a] + NL.join(entry) + NL + text[b:]
    else:
        tail = "}" + NL + NL + "return Arenas"
        assert text.count(tail) == 1, "Config/Arenas.luau: closing of the table not found"
        text = text.replace(tail, NL.join(entry) + NL + tail)
    arenas.write_bytes(text.encode("utf-8"))
    print("LAYOUT_OK", aid, len(mods), "modules,", len(paths), "road(s)")


main()
